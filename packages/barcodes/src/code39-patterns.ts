export const alphabet = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ-. $/+%";

// Standard Code 39 nine-element patterns: high bit first, 1 = wide, alternating bar/space.
const patterns = [
  0x034, 0x121, 0x061, 0x160, 0x031, 0x130, 0x070, 0x025, 0x124, 0x064, 0x109, 0x049, 0x148, 0x019, 0x118, 0x058, 0x00d,
  0x10c, 0x04c, 0x01c, 0x103, 0x043, 0x142, 0x013, 0x112, 0x052, 0x007, 0x106, 0x046, 0x016, 0x181, 0x0c1, 0x1c0, 0x091,
  0x190, 0x0d0, 0x085, 0x184, 0x0c4, 0x0a8, 0x0a2, 0x08a, 0x02a,
] as const;

export function pattern(character: string): number {
  return character === "*" ? 0x094 : patterns[alphabet.indexOf(character)]!;
}

export function checksum(value: string): string {
  let total = 0;
  for (const character of value) total += alphabet.indexOf(character);
  return alphabet[total % 43]!;
}
